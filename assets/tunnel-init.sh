#!/usr/bin/env bash
# Generate Cloudflare Tunnel config + keep-alive jobs for a VPS-FREE rendezvous
# running on the WorkBuddy machine.
#
#   bash tunnel-init.sh bridge.example.com [local-port] [tunnel-uuid]
#
# WRITES FILES ONLY. This script does NOT log in to Cloudflare, create a tunnel,
# change DNS, install cloudflared, or enable any service. Those are external
# actions for the human owner to review and run from the printed runbook.
#
# Overridable for tests / non-standard layouts:
#   MUSE_BRIDGE_JOB_DIR   where launchd/systemd job files go
#   MUSE_BRIDGE_CF_DIR    where cloudflared config goes (default ~/.cloudflared)
#   MB_ROOT_DIR           local mailbox directory
#   MB_TOKEN_FILE         0600 file holding the bearer token
set -euo pipefail

HOSTNAME="${1:?usage: tunnel-init.sh <public-hostname> [local-port] [tunnel-uuid]}"
PORT="${2:-8787}"
TUNNEL_ID="${3:-__TUNNEL_UUID__}"
JOBDIR="${MUSE_BRIDGE_JOB_DIR:-$HOME/Library/LaunchAgents}"
CFDIR="${MUSE_BRIDGE_CF_DIR:-$HOME/.cloudflared}"
SKILL_SCRIPTS="$(cd "$(dirname "$0")/../scripts" && pwd)"
MB_ROOT_DIR="${MB_ROOT_DIR:-$HOME/.local/share/muse-bridge/mail}"
MB_TOKEN_FILE="${MB_TOKEN_FILE:-$HOME/.config/muse-bridge/http-token}"
PY="$(command -v python3 || echo /usr/bin/python3)"
CFBIN="$(command -v cloudflared || echo /usr/local/bin/cloudflared)"
LOGDIR="${MUSE_BRIDGE_STATE:-$HOME/.local/state/muse-bridge}"

case "$HOSTNAME" in
  */*|*" "*|*..*) echo "invalid hostname: $HOSTNAME" >&2; exit 2 ;;
esac
case "$PORT" in ''|*[!0-9]*) echo "invalid port: $PORT" >&2; exit 2 ;; esac

mkdir -p "$JOBDIR" "$CFDIR" "$LOGDIR"
if ! command -v cloudflared >/dev/null 2>&1; then
  echo "NOTE: cloudflared is not on PATH. Files below are still written;" >&2
  echo "      install it before enabling the tunnel job (brew install cloudflared)." >&2
fi

# Never overwrite the user's existing cloudflared config.
CFG="$CFDIR/config.muse-bridge.yml"
if [ -e "$CFG" ]; then
  echo "keeping existing $CFG (review manually, not overwriting)"
else
  cat > "$CFG" <<EOF
# Generated by muse-bridge/tunnel-init.sh. Fill TUNNEL_ID with the real UUID
# from 'cloudflared tunnel create muse-bridge' before enabling the job.
tunnel: $TUNNEL_ID
credentials-file: $CFDIR/$TUNNEL_ID.json
ingress:
  - hostname: $HOSTNAME
    service: http://127.0.0.1:$PORT
  - service: http_status:404
EOF
  chmod 600 "$CFG"
  echo "wrote $CFG"
fi

COMMON_ENV="    <key>MUSE_BRIDGE_STATE</key>\n    <string>$LOGDIR</string>"

if [ "$(uname -s)" = "Darwin" ]; then
  cat > "$JOBDIR/com.user.muse-bridge.serve.plist" <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0"><dict>
    <key>Label</key><string>com.user.muse-bridge.serve</string>
    <key>ProgramArguments</key><array>
        <string>$PY</string>
        <string>$SKILL_SCRIPTS/serve.py</string>
        <string>--root</string><string>$MB_ROOT_DIR</string>
        <string>--port</string><string>$PORT</string>
        <string>--token-file</string><string>$MB_TOKEN_FILE</string>
    </array>
    <key>RunAtLoad</key><true/>
    <key>KeepAlive</key><true/>
    <key>StandardOutPath</key><string>$LOGDIR/serve.log</string>
    <key>StandardErrorPath</key><string>$LOGDIR/serve.err</string>
$(printf '%b' "$COMMON_ENV")
</dict></plist>
EOF
  cat > "$JOBDIR/com.user.muse-bridge.tunnel.plist" <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0"><dict>
    <key>Label</key><string>com.user.muse-bridge.tunnel</string>
    <key>ProgramArguments</key><array>
        <string>$CFBIN</string>
        <string>tunnel</string>
        <string>--config</string><string>$CFG</string>
        <string>run</string>
    </array>
    <key>RunAtLoad</key><true/>
    <key>KeepAlive</key><true/>
    <key>StandardOutPath</key><string>$LOGDIR/tunnel.log</string>
    <key>StandardErrorPath</key><string>$LOGDIR/tunnel.err</string>
</dict></plist>
EOF
  echo "wrote $JOBDIR/com.user.muse-bridge.{serve,tunnel}.plist"
  echo "enable (only after the runbook below is done):"
  echo "  launchctl bootstrap gui/\$(id -u) $JOBDIR/com.user.muse-bridge.serve.plist"
  echo "  launchctl bootstrap gui/\$(id -u) $JOBDIR/com.user.muse-bridge.tunnel.plist"
else
  cat > "$JOBDIR/muse-bridge-serve.service" <<EOF
[Unit]
Description=muse-bridge local HTTP rendezvous
After=network.target
[Service]
ExecStart=$PY $SKILL_SCRIPTS/serve.py --root $MB_ROOT_DIR --port $PORT --token-file $MB_TOKEN_FILE
Restart=always
[Install]
WantedBy=default.target
EOF
  cat > "$JOBDIR/muse-bridge-tunnel.service" <<EOF
[Unit]
Description=muse-bridge Cloudflare Tunnel
After=network-online.target
[Service]
ExecStart=$CFBIN tunnel --config $CFG run
Restart=always
[Install]
WantedBy=default.target
EOF
  echo "wrote $JOBDIR/muse-bridge-{serve,tunnel}.service"
  echo "enable (only after the runbook below is done):"
  echo "  systemctl --user daemon-reload && systemctl --user enable --now muse-bridge-serve muse-bridge-tunnel"
fi

cat <<EOF

=========================== HUMAN RUNBOOK ===========================
Nothing external has been done on your behalf. In order:

1. cloudflared tunnel login
2. cloudflared tunnel create muse-bridge
3. cloudflared tunnel route dns muse-bridge $HOSTNAME
   ^ this changes your public DNS. Review it; this script never runs it.
4. Put the UUID from step 2 into: $CFG
   (and make sure credentials-file points at the matching .json)
5. Create the token ONCE (do not print it anywhere public):
     $PY $SKILL_SCRIPTS/serve.py --root "$MB_ROOT_DIR" --token-file "$MB_TOKEN_FILE" --init-token
   Then give that token to Muse over a separate secure channel.
6. Smoke-test locally before enabling anything:
     curl -sS http://127.0.0.1:$PORT/v2/health
7. Enable the two jobs with the commands printed above.

IMPORTANT LIMIT: the rendezvous lives on THIS machine. When it sleeps or
shuts down, the tunnel drops and the peer cannot WRITE new mail. Mail already
on disk survives; delivery resumes after wake-up. If you need true async
delivery while this machine is off, put serve.py on a free container host or
a VPS instead (see references/no-vps.md).
====================================================================
EOF
